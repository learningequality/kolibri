from .virtual import admitted_virtual_ids

# Fetched from ContentSummaryLog, not from this viewset's ContentNode queryset,
# so a serializer_class would describe the wrong model.
_PROGRESS_VALUES = (
    "content_id",
    "progress",
    "num_question_answered",
    "num_question_answered_correctly",
    "total_questions",
)


class ContentNodeProgressViewset(
    NodeSelectionMixin, TreeQueryMixin, GenericViewSet, ListModelMixin
):
    filter_backends = (DjangoFilterBackend, filters.OrderingFilter)
    ordering_fields: ClassVar[list] = ["last_interacted"]
    ordering = ("lft", "id")
    filterset_class = UserContentNodeFilter
    # Use same pagination class as ContentNodeViewset so we can
    # return identically paginated responses.
    # The only deviation is that we only return the results
    # and not the full pagination object, as we expect
    # that the pagination object generated by the ContentNodeViewset
    # will be used to make subsequent page requests.
    pagination_class = OptionalPagination
    # Only here to avoid warnings from DRF YASG schema generation.
    serializer_class = Serializer

    def get_queryset(self):
        user = self.request.user

        queryset = models.ContentNode.objects.filter(available=True)
        if user.is_anonymous:
            user = None

        return queryset.annotate(
            last_interacted=Subquery(
                ContentSummaryLog.objects.filter(
                    content_id=OuterRef("content_id"), user=user
                ).values_list("end_timestamp")[:1]
            )
        )

    def generate_response(self, request, queryset, virtual_ids=()):
        if request.user.is_anonymous:
            return Response([])
        logs = list(
            ContentSummaryLog.objects.filter(
                Q(
                    content_id__in=queryset.exclude(
                        kind=content_kinds.TOPIC
                    ).values_list("content_id", flat=True)
                )
                | Q(instance_id__in=virtual_ids),
                user=self.request.user,
            )
            .annotate(
                num_question_answered=Subquery(
                    MasteryLog.objects.filter(
                        user=self.request.user,
                        summarylog__content_id=OuterRef("content_id"),
                    )
                    .annotate(
                        num_question_answered=Count("attemptlogs"),
                    )
                    .values("num_question_answered")
                    .order_by("-end_timestamp")[:1]
                ),
                num_question_answered_correctly=Subquery(
                    MasteryLog.objects.filter(
                        user=self.request.user,
                        summarylog__content_id=OuterRef("content_id"),
                    )
                    .annotate(
                        num_question_answered_correctly=Count(
                            "attemptlogs",
                            filter=Q(attemptlogs__correct=1),
                        ),
                    )
                    .values("num_question_answered_correctly")
                    .order_by("-end_timestamp")[:1]
                ),
                total_questions=Subquery(
                    models.ContentNode.objects.filter(
                        content_id=OuterRef("content_id"),
                    ).values("assessmentmetadata__number_of_assessments")[:1]
                ),
            )
            .values(*_PROGRESS_VALUES)
        )
        return Response(logs)

    def list(self, request, *args, **kwargs):
        queryset = self.filter_queryset(self.get_queryset(), narrow_to_selection=False)
        node_ids = selected_node_ids(request)
        if node_ids is None:
            page_queryset = self.paginate_queryset(queryset)
            if page_queryset is not None:
                queryset = page_queryset
            return self.generate_response(request, queryset)
        page_ids = window_ids(
            request,
            admitted_node_ids(node_ids, queryset, self.admits_virtual_nodes()),
        ).page_ids
        real = queryset.filter_by_uuids(page_ids, validate=False)
        real_ids = set(real.values_list("id", flat=True))
        return self.generate_response(
            request, real, [i for i in page_ids if i not in real_ids]
        )

    @action(detail=True)
    def tree(self, request, pk=None):
        try:
            queryset = self.get_tree_queryset(request, pk)
        except Http404:
            if not self.admits_virtual_nodes():
                raise
            virtual_ids = admitted_virtual_ids(
                [pk], self.filter_queryset(self.get_queryset())
            )
            if not virtual_ids:
                raise
            return self.generate_response(
                request, models.ContentNode.objects.none(), virtual_ids
            )
        return self.generate_response(request, queryset)
